#!/usr/bin/env python3
"""Builds the core's geoid table from the EGM96 15-minute grid in PROJ's GTX format.

    python3 tools/geoid_table.py egm96_15.gtx > core/Sources/FlightCore/Geo/GeoidHeights.swift

egm96_15.gtx is in https://download.osgeo.org/proj/proj-datumgrid-1.8.zip, PROJ's copy of NGA's EGM96 grid
(a US Government work in the public domain). The worst error of each area against the grid goes to stderr.
"""
import math
import struct
import sys

# Name, south, north, west, east (past 180 across the Aleutians), step in degrees. Each step is the largest that
# keeps the worst error under 2.5 m, with the south-west corner on the source node where that error is least.
AREAS = [
    ("Contiguous US", 23.75, 50, -125.25, -66, 0.75),
    ("Alaska", 51, 72, 172, 230.5, 0.5),
    ("Hawaii", 18.5, 23, -161, -154.5, 0.25),
    ("Northwestern Hawaiian Islands", 23, 29, -179, -161, 0.5),
    ("Puerto Rico and US Virgin Islands", 17.25, 18.75, -68.25, -64.25, 0.5),
    ("Guam and Northern Mariana Islands", 13, 21, 144.25, 146.25, 0.5),
    ("American Samoa", -15.5, -10.5, -171.25, -167.5, 1.25),
]


def read_gtx(path):
    with open(path, "rb") as f:
        data = f.read()
    south, west, dlat, dlon, rows, cols = struct.unpack(">4d2i", data[:40])
    values = struct.unpack(">%df" % (rows * cols), data[40:40 + 4 * rows * cols])

    def at(lat, lon):
        return values[round((lat - south) / dlat) * cols + round(((lon - west) % 360) / dlon) % cols]
    return at, dlat


def main(path):
    at, source_step = read_gtx(path)
    print("// EGM96 geoid heights from NGA's 15-minute grid, a US Government work in the public domain.")
    print("// Generated by tools/geoid_table.py; do not edit.")
    print("extension Geoid {")
    print("    static let grids: [Grid] = [")
    for name, south, north, west, east, step in AREAS:
        rows = math.ceil((north - south) / step) + 1
        cols = math.ceil((east - west) / step) + 1
        grid = [[round(at(south + i * step, west + j * step)) for j in range(cols)] for i in range(rows)]
        print(f"        // {name}")
        print(f"        Grid(south: {float(south)}, west: {float(west)}, step: {step}, columns: {cols}, heights: [")
        for row in grid:
            print("            " + ", ".join(map(str, row)) + ",")
        print("        ]),")

        # Bilinear from the table at every source node it covers, as Geoid.height reads it.
        worst = 0
        per = round(1 / source_step)
        for a in range(math.ceil(south * per), math.floor((south + (rows - 1) * step) * per) + 1):
            for b in range(math.ceil(west * per), math.floor((west + (cols - 1) * step) * per) + 1):
                y, x = (a / per - south) / step, (b / per - west) / step
                i, j = min(int(y), rows - 2), min(int(x), cols - 2)
                fy, fx = y - i, x - j
                h = ((grid[i][j] * (1 - fx) + grid[i][j + 1] * fx) * (1 - fy)
                     + (grid[i + 1][j] * (1 - fx) + grid[i + 1][j + 1] * fx) * fy)
                worst = max(worst, abs(h - at(a / per, b / per)))
        print(f"{name}: {rows * cols} heights, worst {worst:.2f} m", file=sys.stderr)
        if worst >= 3:
            sys.exit(f"{name}: the table must stay under 3 m from the grid")
    print("    ]")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
