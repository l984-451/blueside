// Generated from FAA type certificate data sheets; each entry names its sheet, revision and section.
// Cruise and burn, where given, are typical figures for the pilot to check against the POH.

/// A starting point the pilot picks by make and model.
public struct AircraftTemplate: Encodable, Equatable, Sendable {
    public var title: String
    public var profile: AircraftProfile

    public init(_ title: String, _ profile: AircraftProfile) {
        self.title = title
        self.profile = profile
    }

    /// Every word of the query is in the title or type, ignoring case, spaces and dashes.
    public func matches(_ query: String) -> Bool {
        func key(_ s: String) -> String { String(s.lowercased().filter { $0.isLetter || $0.isNumber }) }
        let text = key(title + (profile.type ?? ""))
        return query.split(separator: " ").allSatisfy { text.contains(key(String($0))) }
    }
}

